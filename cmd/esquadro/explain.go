package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/patrickluzdev/esquadro/internal/workspace"
)

func runExplain(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("explain", flag.ContinueOnError)
	fs.SetOutput(stderr)
	dir := fs.String("C", ".", "the project folder")
	fs.Usage = func() {
		fmt.Fprintln(stderr, "Usage: esquadro explain [-C dir] <file>")
		fmt.Fprintln(stderr)
		fmt.Fprintln(stderr, "Tells which blueprint and template generated a file, which blueprints it")
		fmt.Fprintln(stderr, "replaced, who contributed to its slots, and whether you edited it.")
		fmt.Fprintln(stderr)
		fs.PrintDefaults()
	}
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() != 1 {
		fs.Usage()
		return 2
	}
	rel := filepath.ToSlash(filepath.Clean(fs.Arg(0)))

	lock, err := workspace.ReadLock(*dir)
	if err != nil {
		fmt.Fprintln(stderr, "esquadro explain:", err)
		return 1
	}
	f, ok := lock.Files[rel]
	if !ok {
		fmt.Fprintf(stderr, "esquadro explain: %s was not generated by esquadro (or not yet: run esquadro gen)\n", rel)
		return 1
	}

	fmt.Fprintln(stdout, rel)
	if f.Hook != "" {
		fmt.Fprintf(stdout, "  written by    hook %s\n", f.Hook)
	} else {
		fmt.Fprintf(stdout, "  generated by  %s, from %s\n", f.Blueprint, path.Join("templates", f.Template))
	}
	if len(f.Replaced) > 0 {
		fmt.Fprintf(stdout, "  replaces      the file of %s\n", strings.Join(f.Replaced, ", then "))
	}
	for _, s := range f.Slots {
		fmt.Fprintf(stdout, "  slot          %s <- %s\n", s.Slot, strings.Join(s.Contributors, ", "))
	}
	fmt.Fprintf(stdout, "  state         %s\n", state(*dir, rel, f))
	return 0
}

func state(dir, rel string, f workspace.LockedFile) string {
	data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
	switch {
	case err != nil && os.IsNotExist(err):
		if f.Once {
			return "yours, and deleted: esquadro will not bring it back"
		}
		return "missing: the next esquadro gen creates it again"
	case err != nil:
		return "unreadable: " + err.Error()
	case f.Once:
		return "yours: generated once, never updated by esquadro"
	case workspace.Hash(data) == f.Hash:
		return "as generated"
	case f.Hook != "":
		return "edited by you since the hook wrote it: esquadro gen stops until you move the change or use -force"
	default:
		return "edited by you since it was generated: esquadro gen will not overwrite it without -force"
	}
}
