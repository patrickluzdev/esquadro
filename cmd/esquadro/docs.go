// runDocs writes the reference pages of the documentation site: one page per
// built-in blueprint, from its manifest, and the CLI, from each command's
// help. It is how the site never disagrees with esquadro; it is not listed
// in esquadro's help.
func runDocs(args []string, _, stderr io.Writer) int {
	if len(args) != 1 {
		fmt.Fprintln(stderr, "Usage: esquadro docs <folder of the site's pages>")
		return 2
	}
	pages, err := referencePages()
	if err != nil {
		fmt.Fprintln(stderr, "esquadro docs:", err)
		return 1
	}
	for name, content := range pages {
		p := filepath.Join(args[0], filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			fmt.Fprintln(stderr, "esquadro docs:", err)
			return 1
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			fmt.Fprintln(stderr, "esquadro docs:", err)
			return 1
		}
	}
	return 0
}

// blueprintOrder lists the built-in blueprints as the site presents them:
// by group, in the order an app lists them.
var blueprintOrder = []string{
	"app", "env", "domain", "http", "worker", "jobs",
	"postgres", "migrations", "store", "testcontainers", "compose",
	"rest", "api_docs", "cors", "security_headers", "rate_limit", "compression", "i18n",
	"observability",
	"docker", "github_actions",
	"git", "branching",
}

// referencePages returns the generated pages by path, relative to the
// site's pages folder.
func referencePages() (map[string]string, error) {
	pages := map[string]string{}
	names, err := fs.Glob(blueprints.FS, "*/"+blueprint.ManifestFile)
	if err != nil {
		return nil, err
	}
	for _, m := range names {
		name := path.Dir(m)
		if !slices.Contains(blueprintOrder, name) {
			return nil, fmt.Errorf("blueprint %s is not in blueprintOrder: add it to its group", name)
		}
	}
	for i, name := range blueprintOrder {
		src, err := fs.ReadFile(blueprints.FS, name+"/"+blueprint.ManifestFile)
		if err != nil {
			return nil, fmt.Errorf("blueprint %s: %w", name, err)
		}
		m, diags := blueprint.ParseManifest(name+"/"+blueprint.ManifestFile, src)
		if m == nil || diags.HasErrors() {
			return nil, fmt.Errorf("blueprint %s: invalid manifest: %v", name, diags)
		}
		pages["blueprints/reference/"+name+".md"] = blueprintPage(m, i+1)
	}
	pages["reference/cli.md"] = cliPage()
	return pages, nil
}

const generated = "<!-- Generated by esquadro docs from the blueprint's manifest: do not edit. -->\n\n"

// blueprintPage documents a manifest: what the blueprint does, how it
// relates to others, its options, annotations, slots and hooks.
func blueprintPage(m *blueprint.Manifest, order int) string {
	var b strings.Builder
	summary := ""
	if len(m.Doc) > 0 {
		summary, _, _ = strings.Cut(strings.Join(m.Doc, " "), ". ")
		summary = strings.TrimSuffix(summary, ".") + "."
	}
	fmt.Fprintf(&b, "---\ntitle: %s\ndescription: %q\nsidebar:\n  order: %d\n---\n\n", m.Name, summary, order)
	b.WriteString(generated)
	b.WriteString(escape(paragraphs(m.Doc)))
	fmt.Fprintf(&b, "\n\n```esquadro\nblueprint %s\n```\n", m.Name)

	if len(m.Requires) > 0 || len(m.Optional) > 0 {
		b.WriteString("\n## Works with\n\n")
		if len(m.Requires) > 0 {
			fmt.Fprintf(&b, "- **Requires** %s: the app must use them too.\n", links(m.Requires))
		}
		if len(m.Optional) > 0 {
			fmt.Fprintf(&b, "- **Works with** %s when the app uses them.\n", links(m.Optional))
		}
	}
	if len(m.Options) > 0 {
		b.WriteString("\n## Options\n\n| Option | Type | Default | |\n|---|---|---|---|\n")
		for _, o := range m.Options {
			def := "*required*"
			if !o.Required {
				def = "`" + valueText(o.Default) + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", o.Name, o.Type, def, cell(o.Doc))
		}
		fmt.Fprintf(&b, "\n```esquadro\nblueprint %s {\n  %s %s\n}\n```\n", m.Name, m.Options[0].Name, example(m.Options[0]))
	}
	if len(m.Env) > 0 {
		b.WriteString("\n## Environment variables\n\nRead when the app starts; see [Environment variables](/esquadro/language/environment/).\n\n| Variable | Type | Value | |\n|---|---|---|---|\n")
		for _, v := range m.Env {
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", envDisplayName(v), envKind(v), escape(envDefaults(v)), cell(v.Doc))
		}
	}
	if len(m.Annotations) > 0 {
		b.WriteString("\n## Annotations\n\n| Where | Key | Type | |\n|---|---|---|---|\n")
		for _, t := range []blueprint.Target{blueprint.TargetApp, blueprint.TargetEntity, blueprint.TargetField, blueprint.TargetRelation, blueprint.TargetJob} {
			spec := m.Annotations[t]
			if spec == nil {
				continue
			}
			for _, k := range spec.Keys {
				fmt.Fprintf(&b, "| %s | `%s` | %s | %s |\n", t, k.Name, k.Type, cell(k.Doc))
			}
		}
		fmt.Fprintf(&b, "\nAn annotation is written `@%s(key value)` on the element.\n", m.Name)
	}
	if len(m.Slots) > 0 {
		b.WriteString("\n## Slots\n\nOther blueprints add code at these points (see [Writing a blueprint](/esquadro/writing-blueprints/#slots)).\n\n| Slot | |\n|---|---|\n")
		for _, s := range m.Slots {
			fmt.Fprintf(&b, "| `%s` | %s |\n", s.Name, cell(s.Doc))
		}
	}
	if len(m.Hooks) > 0 {
		b.WriteString("\n## Hooks\n\n")
		for _, h := range m.Hooks {
			fmt.Fprintf(&b, "- `%s` %s", h.Event, h.Path)
			if len(h.Writes) > 0 {
				fmt.Fprintf(&b, ", writes `%s`", strings.Join(h.Writes, "`, `"))
			}
			if len(h.Edits) > 0 {
				fmt.Fprintf(&b, ", edits `%s`", strings.Join(h.Edits, "`, `"))
			}
			b.WriteString("\n")
		}
	}
	if len(m.GoRequires) > 0 {
		b.WriteString("\n## Go modules\n\n")
		for _, r := range m.GoRequires {
			fmt.Fprintf(&b, "- `%s` %s\n", r.Module, r.Version)
		}
	}
	return b.String()
}

// paragraphs joins doc comment lines into Markdown paragraphs, keeping the
// blank lines between them.
func paragraphs(doc []string) string {
	var parts []string
	var cur []string
	for _, l := range doc {
		if strings.TrimSpace(l) == "" {
			if len(cur) > 0 {
				parts = append(parts, strings.Join(cur, " "))
				cur = nil
			}
			continue
		}
		cur = append(cur, strings.TrimSpace(l))
	}
	if len(cur) > 0 {
		parts = append(parts, strings.Join(cur, " "))
	}
	return strings.Join(parts, "\n\n")
}

// cell is a doc comment on one line of a Markdown table.
func cell(doc []string) string {
	return strings.ReplaceAll(escape(strings.Join(doc, " ")), "|", `\|`)
}

// escape keeps text like <APP>_RATE_LIMIT from being read as HTML.
func escape(s string) string { return strings.ReplaceAll(s, "<", "&lt;") }

func links(deps []blueprint.Dep) string {
	var out []string
	for _, d := range deps {
		out = append(out, fmt.Sprintf("[%s](../%s/)", d.Name, d.Name))
	}
	return strings.Join(out, ", ")
}

// valueText writes an option's default as the .esq file would.
func valueText(v any) string {
	switch x := v.(type) {
	case nil:
		return `""`
	case string:
		return fmt.Sprintf("%q", x)
	case []any:
		var items []string
		for _, it := range x {
			items = append(items, valueText(it))
		}
		return "[" + strings.Join(items, ", ") + "]"
	}
	return fmt.Sprint(v)
}

// example is a value for an option in the page's example: its default, or
// one of its type.
func example(o *blueprint.Spec) string {
	if !o.Required && o.Default != nil {
		if l, ok := o.Default.([]any); !ok || len(l) > 0 {
			return valueText(o.Default)
		}
	}
	switch o.Type {
	case blueprint.TypeInt:
		return "1"
	case blueprint.TypeBool:
		return "true"
	case blueprint.TypeList:
		return `["value"]`
	}
	return `"value"`
}

// cliPage documents every command from its own help, so the page says what
// the binary does.
func cliPage() string {
	var b strings.Builder
	b.WriteString("---\ntitle: CLI\ndescription: Every esquadro command and its flags.\n---\n\n")
	b.WriteString("<!-- Generated by esquadro docs from each command's help: do not edit. -->\n\n")
	for _, c := range commands() {
		if c.hidden {
			continue
		}
		fmt.Fprintf(&b, "## esquadro %s\n\n%s.\n\n", c.name, strings.ToUpper(c.short[:1])+c.short[1:])
		if c.name == "version" {
			b.WriteString("```\nesquadro version\n```\n\n")
			continue
		}
		var help bytes.Buffer
		c.run([]string{"-h"}, &help, &help)
		fmt.Fprintf(&b, "```\n%s\n```\n\n", strings.TrimSpace(help.String()))
		subs := map[string][]command{"blueprint": blueprintCommands(), "env": envCommands()}[c.name]
		for _, sub := range subs {
			help.Reset()
			sub.run([]string{"-h"}, &help, &help)
			fmt.Fprintf(&b, "### esquadro %s %s\n\n%s.\n\n```\n%s\n```\n\n", c.name, sub.name,
				strings.ToUpper(sub.short[:1])+sub.short[1:], strings.TrimSpace(help.String()))
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// envDisplayName is a variable's name as a reference page shows it: with
// the app's prefix as <APP>_.
func envDisplayName(v *project.EnvVar) string {
	if v.Prefixed {
		return "<APP>_" + v.Name
	}
	return v.Name
}

// envKind is a variable's type, with secret and where it is required.
func envKind(v *project.EnvVar) string {
	kind := string(v.Type)
	if v.Secret {
		kind += ", secret"
	}
	switch {
	case v.RequiredOutsideDevelopment:
		kind += ", required outside development"
	case len(v.Required) > 0:
		kind += ", required in " + strings.Join(v.Required, ", ")
	}
	return kind
}

// envDefaults are a variable's declared values, templates shown as they
// are written.
func envDefaults(v *project.EnvVar) string {
	code := func(val any) string {
		shown := envShown(val)
		if strings.HasPrefix(shown, "the ") && (strings.HasSuffix(shown, " option") || strings.HasSuffix(shown, " options")) {
			return shown
		}
		return "`" + shown + "`"
	}
	var parts []string
	if v.Default != nil {
		parts = append(parts, code(v.Default))
	}
	for _, e := range slices.Sorted(maps.Keys(v.ByEnv)) {
		if v.Secret {
			parts = append(parts, "a value in "+e)
			continue
		}
		parts = append(parts, e+": "+code(v.ByEnv[e]))
	}
	if v.Generate > 0 {
		parts = append(parts, "generated in development")
	}
	if len(parts) == 0 {
		return "-"
	}
	return strings.Join(parts, "; ")
}

func envShown(val any) string {
	switch val := val.(type) {
	case []string:
		return strings.Join(val, ",")
	case string:
		// An option's value, from a template: name the option.
		if m := optionRef.FindStringSubmatch(val); m != nil && strings.TrimSpace(val) == m[0] {
			return "the " + m[1] + " option"
		}
		if strings.Contains(val, "{{") {
			return "the app's, from its blueprints and options"
		}
		return val
	}
	return fmt.Sprint(val)
}

var optionRef = regexp.MustCompile(`\{\{\s*\.Options\.([a-z_]+)\s*\}\}`)
