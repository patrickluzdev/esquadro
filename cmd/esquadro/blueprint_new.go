var blueprintName = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// The test project of a blueprint, in its testdata folder: an app with the
// blueprint (written as testRef, its folder from the project's esquadro/)
// and a small model; expected holds what the blueprint generates for it.
const (
	testProject  = "testdata/project"
	testExpected = "testdata/expected"
	testRef      = "../../.."
)

func runBlueprintNew(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("blueprint new", flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() {
		fmt.Fprintln(stderr, "Usage: esquadro blueprint new <name> [dir]")
		fmt.Fprintln(stderr)
		fmt.Fprintln(stderr, "Starts a blueprint of your own in esquadro/blueprints/<name> of the project")
		fmt.Fprintln(stderr, "in dir (default: the current directory) and adds it to the app: a manifest,")
		fmt.Fprintln(stderr, "a template for the whole project and one for each entity, code added to the")
		fmt.Fprintln(stderr, "app's Taskfile, and a test project with what the blueprint generates for")
		fmt.Fprintln(stderr, "it, which esquadro blueprint test checks. Change them to make it yours.")
	}
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() < 1 || fs.NArg() > 2 {
		fmt.Fprintln(stderr, "esquadro blueprint new: expected the blueprint's name and, optionally, the project's directory")
		fs.Usage()
		return 2
	}
	name, dir := fs.Arg(0), "."
	if fs.NArg() == 2 {
		dir = fs.Arg(1)
	}
	if !blueprintName.MatchString(name) {
		fmt.Fprintf(stderr, "esquadro blueprint new: %q is not a blueprint name: use lower-case letters, digits and _, e.g. billing\n", name)
		return 2
	}
	if !isProject(dir) {
		fmt.Fprintf(stderr, "esquadro blueprint new: %s is not a project (it has no %s/ folder); create one with esquadro new\n", dir, workspace.Dir)
		return 1
	}
	bpDir := filepath.Join(dir, workspace.Dir, "blueprints", name)
	if _, err := os.Stat(bpDir); err == nil {
		fmt.Fprintf(stderr, "esquadro blueprint new: %s already exists\n", bpDir)
		return 1
	}
	for file, content := range newBlueprintFiles(name) {
		full := filepath.Join(bpDir, filepath.FromSlash(file))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			fmt.Fprintf(stderr, "esquadro blueprint new: %v\n", err)
			return 1
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			fmt.Fprintf(stderr, "esquadro blueprint new: %v\n", err)
			return 1
		}
	}
	fmt.Fprintf(stdout, "created %s/\n", bpDir)
	var quiet bytes.Buffer
	if code := blueprintTest(bpDir, true, &quiet, stderr); code != 0 {
		fmt.Fprint(stderr, quiet.String())
		return code
	}
	if code := runAdd([]string{"-no-gen", "./blueprints/" + name, dir}, stdout, stderr); code != 0 {
		return code
	}
	fmt.Fprintln(stdout)
	fmt.Fprintf(stdout, "Next: change it in %s/, run esquadro gen to see what it generates in the project,\n", bpDir)
	fmt.Fprintf(stdout, "and esquadro blueprint test %s to check it against its test project.\n", name)
	return 0
}

// newBlueprintFiles are the files of a new blueprint, by path.
func newBlueprintFiles(name string) map[string]string {
	pkg := strings.ReplaceAll(name, "_", "")
	r := strings.NewReplacer("NAME", name, "PKG", pkg)
	files := map[string]string{
		"blueprint.esq": `/// NAME: say here what this blueprint does, for the people who use it. The
/// first sentence is its summary in esquadro blueprint list; esquadro
/// blueprint info shows it all.
blueprint NAME {
  version "0.1.0"
  requires app

  /// The greeting of the generated code. A blueprint's options are
  /// written in the app's block: blueprint "./blueprints/NAME" { greeting "Hi" }.
  option greeting string default("Hello")

  /// Lines other blueprints add to the Greetings function: a slot is a
  /// point where they add code, with a file slots/NAME.greetings.tmpl.
  slot "NAME.greetings"
}
`,
		// One file for the project.
		"templates/internal/PKG/PKG.go.tmpl": `// Package PKG is generated by the NAME blueprint, from
// esquadro/blueprints/NAME/templates/internal/PKG/PKG.go.tmpl.
package PKG

// Greeting is the greeting option of the blueprint.
const Greeting = {{printf "%q" .Options.greeting}}

// Greetings lists a greeting for each entity of {{.App.Label}}.
func Greetings() []string {
	return []string{
{{- range .Entities}}
		Greeting + ", {{.Label}}",
{{- end}}
{{- with slot "NAME.greetings" .}}
{{.}}
{{- end}}
	}
}
`,
		// One file for each entity: the folder or file name says so.
		"templates/internal/PKG/{{.Entity.Snake}}.go.tmpl": `package PKG

// {{.Entity.Pascal}}Fields are the fields of {{.Entity.Label}}.
var {{.Entity.Pascal}}Fields = []string{
{{- range .Entity.Fields}}
	{{printf "%q" .Snake}},
{{- end}}
}
`,
		// A file for the user: written once, then theirs.
		"templates/internal/PKG/notes.md.once.tmpl": `# Notes on PKG

Written once by the NAME blueprint: this file is yours.
`,
		// Code added to the app blueprint's app.tasks slot.
		"slots/app.tasks.tmpl": `  NAME:greetings:
    desc: List the greetings of the NAME blueprint
    cmds:
      - go doc ./internal/PKG Greetings
`,
		testProject + "/esquadro/app.esq": `// The project esquadro blueprint test generates: its files from the
// blueprint must be those of ../expected.
app demo {
  module "example.com/demo"

  blueprint app
  blueprint "` + testRef + `" {
    greeting "Hi"
  }
}
`,
		testProject + "/esquadro/catalog.esq": `package catalog

entity Product {
  name  string required
  price decimal
}

entity Category {
  name string required
}
`,
	}
	out := map[string]string{}
	for p, c := range files {
		out[r.Replace(p)] = r.Replace(c)
	}
	return out
}

func runBlueprintTest(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("blueprint test", flag.ContinueOnError)
	fs.SetOutput(stderr)
	update := fs.Bool("update", false, "make the generated files the expected ones")
	fs.Usage = func() {
		fmt.Fprintln(stderr, "Usage: esquadro blueprint test [-update] [blueprint]")
		fmt.Fprintln(stderr)
		fmt.Fprintln(stderr, "Generates the blueprint's test project (testdata/project) in a temporary")
		fmt.Fprintln(stderr, "folder and compares the files the blueprint wrote with testdata/expected.")
		fmt.Fprintln(stderr, "The blueprint is a folder, or a name of the project's esquadro/blueprints;")
		fmt.Fprintln(stderr, "by default, the current folder.")
		fmt.Fprintln(stderr)
		fs.PrintDefaults()
	}
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() > 1 {
		fs.Usage()
		return 2
	}
	bpDir := "."
	if fs.NArg() == 1 {
		bpDir = fs.Arg(0)
		if _, err := os.Stat(filepath.Join(bpDir, blueprint.ManifestFile)); err != nil {
			bpDir = filepath.Join(workspace.Dir, "blueprints", fs.Arg(0))
		}
	}
	if _, err := os.Stat(filepath.Join(bpDir, blueprint.ManifestFile)); err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %s has no %s\n", bpDir, blueprint.ManifestFile)
		return 1
	}
	return blueprintTest(bpDir, *update, stdout, stderr)
}

// blueprintTest generates the test project of the blueprint in bpDir and
// compares, or with update replaces, its expected files.
func blueprintTest(bpDir string, update bool, stdout, stderr io.Writer) int {
	abs, err := filepath.Abs(bpDir)
	if err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
		return 1
	}
	src := filepath.Join(abs, filepath.FromSlash(testProject))
	if _, err := os.Stat(src); err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %s has no test project (%s)\n", bpDir, testProject)
		return 1
	}
	tmp, err := os.MkdirTemp("", "esquadro-blueprint-test-")
	if err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
		return 1
	}
	defer os.RemoveAll(tmp)
	if err := os.CopyFS(tmp, os.DirFS(src)); err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
		return 1
	}
	// The copy is elsewhere: point it at the blueprint's folder.
	esqs, _ := filepath.Glob(filepath.Join(tmp, workspace.Dir, "*.esq"))
	for _, f := range esqs {
		b, _ := os.ReadFile(f)
		os.WriteFile(f, bytes.ReplaceAll(b, []byte(strconv.Quote(testRef)), []byte(strconv.Quote(abs))), 0o644)
	}
	var out bytes.Buffer
	if code := runGen([]string{"-trust", tmp}, &out, &out); code != 0 {
		fmt.Fprintf(stderr, "esquadro blueprint test: generating the test project failed:\n%s", out.String())
		return 1
	}
	lock, err := workspace.ReadLock(tmp)
	if err != nil {
		fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
		return 1
	}
	name := ""
	for _, b := range lock.Blueprints {
		if b.Location == abs || strings.HasSuffix(b.Location, abs) {
			name = b.Name
		}
	}
	got := map[string][]byte{}
	for p, f := range lock.Files {
		if f.Blueprint == name {
			if got[p], err = os.ReadFile(filepath.Join(tmp, filepath.FromSlash(p))); err != nil {
				fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
				return 1
			}
		}
	}
	expected := filepath.Join(abs, filepath.FromSlash(testExpected))
	if update {
		if err := os.RemoveAll(expected); err != nil {
			fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
			return 1
		}
		for p, content := range got {
			full := filepath.Join(expected, filepath.FromSlash(p))
			os.MkdirAll(filepath.Dir(full), 0o755)
			if err := os.WriteFile(full, content, 0o644); err != nil {
				fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
				return 1
			}
		}
		fmt.Fprintf(stdout, "%s: wrote %s expected in %s\n", name, count(len(got), "file", "files"), filepath.Join(bpDir, filepath.FromSlash(testExpected)))
		return 0
	}
	want := map[string][]byte{}
	err = filepath.WalkDir(expected, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(expected, p)
		want[filepath.ToSlash(rel)], err = os.ReadFile(p)
		return err
	})
	if err != nil && !os.IsNotExist(err) {
		fmt.Fprintf(stderr, "esquadro blueprint test: %v\n", err)
		return 1
	}
	var problems []string
	paths := slices.Sorted(func(yield func(string) bool) {
		seen := map[string]bool{}
		for _, m := range []map[string][]byte{got, want} {
			for p := range m {
				if !seen[p] {
					seen[p] = true
					if !yield(p) {
						return
					}
				}
			}
		}
	})
	for _, p := range paths {
		g, inGot := got[p]
		w, inWant := want[p]
		switch {
		case !inWant:
			problems = append(problems, fmt.Sprintf("generated, not expected: %s\n", p))
		case !inGot:
			problems = append(problems, fmt.Sprintf("expected, not generated: %s\n", p))
		case !bytes.Equal(g, w):
			problems = append(problems, workspace.Diff(p, w, g))
		}
	}
	if len(problems) > 0 {
		for _, p := range problems {
			fmt.Fprint(stdout, p)
		}
		fmt.Fprintf(stderr, "\n%s: FAIL, %s; if the new output is right: esquadro blueprint test -update\n", name, count(len(problems), "difference", "differences"))
		return 1
	}
	fmt.Fprintf(stdout, "%s: ok, %s as expected\n", name, count(len(got), "file", "files"))
	return 0
}
