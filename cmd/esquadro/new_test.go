func TestNewWritesTheEsqFiles(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "my-shop")
	var out, errOut bytes.Buffer
	// Flags may follow the name.
	code := run([]string{"new", dir, "-module", "example.com/me/shop", "-blueprints", "app, postgres", "-no-git", "-no-gen"}, &out, &errOut)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, errOut.String())
	}
	app, err := os.ReadFile(filepath.Join(dir, "esquadro", "app.esq"))
	if err != nil {
		t.Fatal(err)
	}
	want := "/// My shop, generated by esquadro.\napp my_shop {\n  module \"example.com/me/shop\"\n\n" +
		"  // the program, its modules and how it runs\n  blueprint app\n\n" +
		"  // PostgreSQL: connection, migrations, use cases, tests and local services\n  blueprint postgres\n}\n"
	if string(app) != want {
		t.Fatalf("app.esq:\n%s\nwant:\n%s", app, want)
	}
	if code := run([]string{"check", dir}, &out, &errOut); code != 0 {
		t.Fatalf("check: %s", errOut.String())
	}
	// And formatted as esquadro fmt writes it.
	if code := run([]string{"fmt", "-check", filepath.Join(dir, "esquadro")}, &out, &errOut); code != 0 {
		t.Fatalf("fmt: %s", errOut.String())
	}
	if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
		t.Fatal("-no-git created a repository")
	}
}

func TestNewWritesTheSmallestProject(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "shop")
	var out, errOut bytes.Buffer
	if code := run([]string{"new", "-module", "example.com/shop", "-no-gen", dir}, &out, &errOut); code != 0 {
		t.Fatalf("exit %d: %s", code, errOut.String())
	}
	app, _ := os.ReadFile(filepath.Join(dir, "esquadro", "app.esq"))
	want := "/// Shop, generated by esquadro.\napp shop {\n  module \"example.com/shop\"\n\n" +
		"  blueprint app\n  blueprint env\n  blueprint git {\n    initial_commit true\n  }\n\n" +
		"  // Add more with esquadro add <blueprint>; see them with esquadro blueprint list.\n}\n"
	if string(app) != want {
		t.Fatalf("app.esq:\n%s", app)
	}
	if entries, _ := os.ReadDir(filepath.Join(dir, "esquadro")); len(entries) != 1 {
		t.Fatalf("%d files: the smallest project has no model", len(entries))
	}
	if !strings.Contains(out.String(), "esquadro add <blueprint>") {
		t.Fatalf("next steps: %s", out.String())
	}
	if code := run([]string{"check", dir}, &out, &errOut); code != 0 {
		t.Fatalf("check: %s", errOut.String())
	}
	if code := run([]string{"fmt", "-check", filepath.Join(dir, "esquadro")}, &out, &errOut); code != 0 {
		t.Fatalf("fmt: %s", errOut.String())
	}
}

func TestNewFromEachStarter(t *testing.T) {
	for _, starter := range starterNames() {
		t.Run(starter, func(t *testing.T) {
			if starterAbout(starter) == "" || len(starterBlueprints(starter)) == 0 {
				t.Fatal("the starter has no about or no blueprints")
			}
			for _, git := range []bool{true, false} {
				dir := filepath.Join(t.TempDir(), "my-shop")
				args := []string{"new", "-starter", starter, "-module", "example.com/shop", "-no-gen", dir}
				if !git {
					args = append(args, "-no-git")
				}
				var out, errOut bytes.Buffer
				if code := run(args, &out, &errOut); code != 0 {
					t.Fatalf("exit %d: %s", code, errOut.String())
				}
				app, _ := os.ReadFile(filepath.Join(dir, "esquadro", "app.esq"))
				if !strings.HasPrefix(string(app), "/// My shop, generated by esquadro.\napp my_shop {") ||
					strings.Contains(string(app), "blueprint git {") != git {
					t.Fatalf("git %v, app.esq:\n%s", git, app)
				}
				if code := run([]string{"check", dir}, &out, &errOut); code != 0 {
					t.Fatalf("check: %s", errOut.String())
				}
				if code := run([]string{"fmt", "-check", filepath.Join(dir, "esquadro")}, &out, &errOut); code != 0 {
					t.Fatalf("fmt: %s%s", out.String(), errOut.String())
				}
			}
		})
	}
}

func TestNewRefuses(t *testing.T) {
	full := filepath.Join(t.TempDir(), "shop")
	if err := os.Mkdir(full, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(full, "x"), nil, 0o644); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		args []string
		code int
		msg  string
	}{
		{[]string{"new"}, 2, "expected the project's name"},
		{[]string{"new", "a", "b"}, 2, "got 2 arguments"},
		{[]string{"new", "-no-gen", "My_Shop"}, 2, "is not a project name"},
		{[]string{"new", "-no-gen", "-blueprints", " , ", "shop"}, 2, "-blueprints is empty"},
		{[]string{"new", "-no-gen", "-no-git", full}, 1, "is not empty"},
		{[]string{"new", "-no-gen", "-starter", "api", "-blueprints", "app", "shop"}, 2, "not both"},
		{[]string{"new", "-no-gen", "-starter", "web", "shop"}, 2, "the starters are api, worker, cli"},
	} {
		var out, errOut bytes.Buffer
		if code := run(tc.args, &out, &errOut); code != tc.code || !strings.Contains(errOut.String(), tc.msg) {
			t.Errorf("%v: exit %d, %q", tc.args, code, errOut.String())
		}
	}
}
