// setLockVersion makes a project look generated by esquadro v.
func setLockVersion(t *testing.T, dir, v string) {
	t.Helper()
	path := filepath.Join(dir, "esquadro", "lock.json")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var lock map[string]any
	if err := json.Unmarshal(data, &lock); err != nil {
		t.Fatal(err)
	}
	lock["esquadro"] = v
	data, _ = json.MarshalIndent(lock, "", "  ")
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestGenAsksForUpgradeAcrossReleases(t *testing.T) {
	defer func(v string) { version.Version = v }(version.Version)
	version.Version = "v0.8.0"
	dir := demoProject(t)
	if code, _, errOut := gen(t, dir); code != 0 {
		t.Fatal(errOut)
	}

	// From an older release: gen stops, upgrade shows what changed and generates.
	setLockVersion(t, dir, "v0.7.0")
	if code, _, errOut := gen(t, dir); code == 0 || !strings.Contains(errOut, "esquadro upgrade") {
		t.Fatalf("gen over a project of v0.7.0: %d\n%s", code, errOut)
	}
	var out, errOut strings.Builder
	if code := run([]string{"upgrade", dir}, &out, &errOut); code != 0 {
		t.Fatal(errOut.String())
	}
	if !strings.Contains(out.String(), "From esquadro v0.7.0 to v0.8.0") || !strings.Contains(out.String(), "## Breaking") {
		t.Fatalf("upgrade showed:\n%s", out.String())
	}
	if lock, _ := os.ReadFile(filepath.Join(dir, "esquadro", "lock.json")); !strings.Contains(string(lock), `"esquadro": "v0.8.0"`) {
		t.Fatalf("the lock is not of v0.8.0:\n%s", lock)
	}
	if code, _, errOut := gen(t, dir); code != 0 {
		t.Fatalf("gen after the upgrade: %s", errOut)
	}

	// From a newer release: neither generates.
	setLockVersion(t, dir, "v0.9.0")
	if code, _, errOut := gen(t, dir); code == 0 || !strings.Contains(errOut, "install esquadro v0.9.0") {
		t.Fatalf("gen over a project of v0.9.0: %d\n%s", code, errOut)
	}
	if code := run([]string{"upgrade", dir}, &out, &errOut); code == 0 {
		t.Fatal("upgrade went back to an older esquadro")
	}
}

func TestGenDescribesThePlanAsJSON(t *testing.T) {
	dir := demoProject(t)
	if code, _, errOut := gen(t, dir); code != 0 {
		t.Fatal(errOut)
	}
	os.WriteFile(filepath.Join(dir, "README.md"), []byte("# Shop\n\nMine.\n"), 0o644)
	tmpl := filepath.Join(dir, "esquadro/blueprints/demo/templates/catalog/{{.Entity.Snake}}.go.tmpl")
	os.WriteFile(tmpl, []byte("package catalog\n\n// {{.Entity.Pascal}} is generated, v2.\ntype {{.Entity.Pascal}} struct{}\n"), 0o644)

	out := t.TempDir()
	code, stdout, errOut := gen(t, "-dry-run", "-json", "-out", out, dir)
	if code != 0 {
		t.Fatal(errOut)
	}
	var p struct {
		Versions string `json:"versions"`
		Actions  []struct {
			Path, Change, New string
			Once              bool
		} `json:"actions"`
		Counts map[string]int `json:"counts"`
	}
	if err := json.Unmarshal([]byte(stdout), &p); err != nil {
		t.Fatalf("%v\n%s", err, stdout)
	}
	if p.Counts["update"] != 2 || len(p.Actions) != 3 {
		t.Fatalf("plan:\n%s", stdout)
	}
	for _, a := range p.Actions {
		switch a.Path {
		case "catalog/product.go":
			data, err := os.ReadFile(filepath.Join(out, a.New))
			if a.Change != "update" || err != nil || !strings.Contains(string(data), "v2") {
				t.Fatalf("product.go: %+v %v %s", a, err, data)
			}
		case "README.md":
			if a.Change != "keep" || !a.Once || a.New != "" {
				t.Fatalf("README.md: %+v", a)
			}
		}
	}
	if data, _ := os.ReadFile(filepath.Join(dir, "catalog/product.go")); strings.Contains(string(data), "v2") {
		t.Fatal("-json wrote to the project")
	}
	if code, _, _ := gen(t, "-json", dir); code != 2 {
		t.Fatal("-json without -dry-run")
	}
}

func TestCheckUniqueJobs(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "billing")
	if code, _, errOut := esq(t, "new", "-starter", "worker", "-module", "example.com/billing", "-no-git", "-no-gen", dir); code != 0 {
		t.Fatal(errOut)
	}
	model := filepath.Join(dir, "esquadro", "billing.esq")
	base := read(t, model)
	for name, tc := range map[string]struct{ job, want string }{
		"ok":      {"job Retry {\n  invoice_id uuid required\n  @jobs(unique_by [invoice_id], unique_for \"7d\", unique_while queued)\n}\n", ""},
		"by":      {"job Retry {\n  invoice_id uuid required\n  @jobs(unique_by [invoice])\n}\n", "unique_by: invoice is not an argument of Retry"},
		"for":     {"job Retry {\n  invoice_id uuid required\n  @jobs(unique, unique_for \"soon\")\n}\n", `unique_for of Retry: "soon" is not a period`},
		"while":   {"job Retry {\n  invoice_id uuid required\n  @jobs(unique, unique_while done)\n}\n", "unique_while done of Retry is not ever or queued"},
		"neither": {"job Retry {\n  invoice_id uuid required\n  @jobs(unique_for \"1h\")\n}\n", "Retry has unique_for or unique_while but is not unique"},
	} {
		os.WriteFile(model, []byte(base+"\n"+tc.job), 0o644)
		code, _, errOut := esq(t, "check", dir)
		if tc.want == "" && code != 0 || tc.want != "" && (code == 0 || !strings.Contains(errOut, tc.want)) {
			t.Errorf("%s: exit %d, want %q in:\n%s", name, code, tc.want, errOut)
		}
	}
}

