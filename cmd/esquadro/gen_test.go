package main

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"
)

// demoProject writes a project with a local blueprint that generates one file
// per entity and a README owned by the user.
func demoProject(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write := func(path, content string) {
		full := filepath.Join(dir, path)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("shop.esq", `package catalog

app shop {
  module "github.com/example/shop"
  blueprint "./blueprints/demo"
}

entity Product {
  name string
}

entity Category {
  name string
}
`)
	write("blueprints/demo/blueprint.esq", "blueprint demo {\n  version \"0.1.0\"\n}\n")
	write("blueprints/demo/templates/catalog/{{.Entity.Snake}}.go.tmpl", "package catalog\n\n// {{.Entity.Pascal}} is generated.\ntype {{.Entity.Pascal}} struct{}\n")
	write("blueprints/demo/templates/README.md.once.tmpl", "# {{.App.Pascal}}\n")
	return dir
}

func gen(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errOut strings.Builder
	code := run(append([]string{"gen"}, args...), &out, &errOut)
	return code, out.String(), errOut.String()
}

func explain(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var out, errOut strings.Builder
	code := run(append([]string{"explain"}, args...), &out, &errOut)
	return code, out.String(), errOut.String()
}

func TestGenWritesThenRespectsEdits(t *testing.T) {
	dir := demoProject(t)

	code, out, errOut := gen(t, dir)
	if code != 0 {
		t.Fatalf("exit %d\n%s%s", code, out, errOut)
	}
	for _, want := range []string{"create    README.md", "create    catalog/product.go", "create    catalog/category.go", "3 created, 0 updated, 0 deleted, 0 unchanged"} {
		if !strings.Contains(out, want) {
			t.Errorf("stdout missing %q:\n%s", want, out)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, ".esquadro/lock.json")); err != nil {
		t.Fatal("no lockfile")
	}

	// Running again changes nothing.
	if code, out, _ := gen(t, dir); code != 0 || !strings.Contains(out, "0 created, 0 updated, 0 deleted, 2 unchanged, 1 kept") {
		t.Fatalf("second run: exit %d\n%s", code, out)
	}

	// An edited file stops the next generation that would change it.
	product := filepath.Join(dir, "catalog/product.go")
	os.WriteFile(product, []byte("package catalog\n\n// mine\n"), 0o644)
	tmpl := filepath.Join(dir, "blueprints/demo/templates/catalog/{{.Entity.Snake}}.go.tmpl")
	os.WriteFile(tmpl, []byte("package catalog\n\n// {{.Entity.Pascal}} is generated, v2.\ntype {{.Entity.Pascal}} struct{}\n"), 0o644)

	code, out, errOut = gen(t, dir)
	if code != 1 || !strings.Contains(out, "conflict  catalog/product.go  (edited since esquadro generated it)") ||
		!strings.Contains(errOut, "Nothing was written") {
		t.Fatalf("exit %d\n%s%s", code, out, errOut)
	}
	if data, _ := os.ReadFile(filepath.Join(dir, "catalog/category.go")); strings.Contains(string(data), "v2") {
		t.Fatal("with a conflict, no file may be written")
	}

	// The dry run shows the diffs and writes nothing.
	code, out, _ = gen(t, "-dry-run", dir)
	if code != 0 || !strings.Contains(out, "-// mine") || !strings.Contains(out, "+// Category is generated, v2.") {
		t.Fatalf("dry run: exit %d\n%s", code, out)
	}

	// explain tells where the file came from and that it was edited.
	code, out, _ = explain(t, "-C", dir, "catalog/product.go")
	if code != 0 || !strings.Contains(out, "generated by  demo, from templates/catalog/{{.Entity.Snake}}.go.tmpl") ||
		!strings.Contains(out, "edited by you") {
		t.Fatalf("explain: exit %d\n%s", code, out)
	}

	// -force overwrites.
	if code, out, errOut := gen(t, "-force", dir); code != 0 {
		t.Fatalf("force: exit %d\n%s%s", code, out, errOut)
	}
	if data, _ := os.ReadFile(product); !strings.Contains(string(data), "v2") {
		t.Fatalf("product.go = %s", data)
	}
	if code, out, _ := explain(t, "-C", dir, "catalog/product.go"); code != 0 || !strings.Contains(out, "as generated") {
		t.Fatalf("explain after force:\n%s", out)
	}
}

func TestGenDeletesFilesOfRemovedEntities(t *testing.T) {
	dir := demoProject(t)
	if code, _, errOut := gen(t, dir); code != 0 {
		t.Fatal(errOut)
	}
	esq := filepath.Join(dir, "shop.esq")
	src, _ := os.ReadFile(esq)
	os.WriteFile(esq, []byte(strings.Replace(string(src), "entity Category {\n  name string\n}\n", "", 1)), 0o644)

	code, out, errOut := gen(t, dir)
	if code != 0 || !strings.Contains(out, "delete    catalog/category.go") {
		t.Fatalf("exit %d\n%s%s", code, out, errOut)
	}
	if _, err := os.Stat(filepath.Join(dir, "catalog/category.go")); !os.IsNotExist(err) {
		t.Fatal("category.go was not deleted")
	}
}

func TestExplainUnknownFile(t *testing.T) {
	dir := demoProject(t)
	code, _, errOut := explain(t, "-C", dir, "nope.go")
	if code != 1 || !strings.Contains(errOut, "nope.go was not generated by esquadro") {
		t.Fatalf("exit %d, %q", code, errOut)
	}
}

func TestGenStopsOnTemplateErrors(t *testing.T) {
	dir := demoProject(t)
	os.WriteFile(filepath.Join(dir, "blueprints/demo/templates/README.md.once.tmpl"), []byte("{{.App.Nope}}\n"), 0o644)
	code, _, errOut := gen(t, dir)
	if code != 1 || !strings.Contains(errOut, "README.md.once.tmpl:1:") {
		t.Fatalf("exit %d, %q", code, errOut)
	}
	if _, err := os.Stat(filepath.Join(dir, ".esquadro")); !os.IsNotExist(err) {
		t.Fatal("nothing may be written when templates fail")
	}
}

func TestGenRunsPostGenHooks(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("hook scripts are POSIX shell")
	}
	dir := demoProject(t)
	os.WriteFile(filepath.Join(dir, "blueprints/demo/blueprint.esq"),
		[]byte("blueprint demo {\n  version \"0.1.0\"\n  hook post-gen \"hooks/stamp\" writes \"gen/**\"\n}\n"), 0o644)
	os.MkdirAll(filepath.Join(dir, "blueprints/demo/hooks"), 0o755)
	os.WriteFile(filepath.Join(dir, "blueprints/demo/hooks/stamp"),
		[]byte("#!/bin/sh\ncat >/dev/null\nmkdir -p gen\necho stamped > gen/stamp.txt\nprintf '{\"messages\":[{\"text\":\"stamped\"}]}'\n"), 0o755)

	code, out, errOut := gen(t, "-dry-run", dir)
	if code != 0 || !strings.Contains(out, "run       demo post-gen hooks/stamp  (after writing; may change gen/**)") {
		t.Fatalf("dry run: exit %d\n%s%s", code, out, errOut)
	}
	if _, err := os.Stat(filepath.Join(dir, "gen")); !os.IsNotExist(err) {
		t.Fatal("a dry run must not run post-gen hooks")
	}

	code, out, errOut = gen(t, dir)
	if code != 0 || !strings.Contains(errOut, "demo post-gen hooks/stamp: info: stamped") {
		t.Fatalf("exit %d\n%s%s", code, out, errOut)
	}
	if data, _ := os.ReadFile(filepath.Join(dir, "gen/stamp.txt")); string(data) != "stamped\n" {
		t.Fatalf("stamp = %q", data)
	}
	if code, out, _ := explain(t, "-C", dir, "gen/stamp.txt"); code != 0 ||
		!strings.Contains(out, "written by    hook demo post-gen hooks/stamp") || !strings.Contains(out, "as generated") {
		t.Fatalf("explain: %s", out)
	}
}

func TestGenSavesTheProjectForTheNextRun(t *testing.T) {
	dir := demoProject(t)
	snapshot := filepath.Join(dir, ".esquadro/model.json")
	if code, _, errOut := gen(t, "-dry-run", dir); code != 0 {
		t.Fatal(errOut)
	}
	if _, err := os.Stat(snapshot); !os.IsNotExist(err) {
		t.Fatal("a dry run must not save the project")
	}
	if code, _, errOut := gen(t, dir); code != 0 {
		t.Fatal(errOut)
	}
	data, err := os.ReadFile(snapshot)
	if err != nil || !strings.Contains(string(data), `"pascal": "Product"`) {
		t.Fatalf("snapshot: %v\n%s", err, data)
	}
}
